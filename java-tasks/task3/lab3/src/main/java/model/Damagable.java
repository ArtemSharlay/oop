package model;

/**
 * Интерфейс для объектов, которые могут быть повреждены или уничтожены.
 * Любой игровой объект, реализующий этот интерфейс, может быть уничтожен,
 * например, взрывом бомбы.
 *
 * @see Bomb
 * @see Player
 * @see Enemy
 */
public interface Damagable {

    /**
     * Помечает объект как уничтоженный.
     * После вызова этого метода объект должен быть удален из игрового мира
     * при следующем обновлении состояния игры.
     */
    void setDead();
}