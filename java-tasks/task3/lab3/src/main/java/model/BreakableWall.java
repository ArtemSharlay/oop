package model;

/**
 * Класс, представляющий разрушаемую стену в игре.
 * Разрушаемые стены являются игровыми объектами, которые могут быть уничтожены
 * взрывом бомбы. При уничтожении освобождают проход для игрока и дают очки.
 * Реализует интерфейс {@link Damagable} (повреждаемый объект).

 * @see GameObject
 * @see Damagable
 * @see Wall
 * @see Bomb
 */
public class BreakableWall extends GameObject implements Damagable {

    /**
     * Конструктор разрушаемой стены.
     * Создает новый объект разрушаемой стены в указанных координатах.
     *
     * @param x Координата X (столбец) на игровой карте
     * @param y Координата Y (строка) на игровой карте
     */
    public BreakableWall(int x, int y) {
        super(x, y);
    }

    /**
     * Помечает разрушаемую стену как уничтоженную.
     * Устанавливает флаг {@code dead} в значение {@code true},
     * после чего стена будет удалена из игрового мира при следующем обновлении.
     * Метод вызывается при попадании стены в зону взрыва бомбы.
     *
     * <p>При уничтожении разрушаемой стены:
     * <ul>
     *   <li>Ячейка на карте становится пустой (TileType.EMPTY)</li>
     *   <li>Игрок получает 100 очков (начисление происходит в классе Bomb)</li>
     *   <li>Открывается проход для перемещения игрока и врагов</li>
     * </ul>
     *
     * @see Damagable#setDead()
     * @see Bomb#setTouched(GameModel, java.util.List)
     */
    public void setDead() {
        this.dead = true;
    }
}